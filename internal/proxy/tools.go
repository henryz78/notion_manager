// buildToolList preserves the complete client-provided description and schema.
func buildToolList(tools []Tool) string {
	var sb strings.Builder
	for _, t := range tools {
		sb.WriteString(fmt.Sprintf("Label: %s", t.Function.Name))
		if t.Function.Description != "" {
			sb.WriteString(fmt.Sprintf(" - %s", t.Function.Description))
		}
		if t.Function.Parameters != nil {
			params, _ := json.Marshal(t.Function.Parameters)
			sb.WriteString(fmt.Sprintf("\nArgument schema: %s", string(params)))
		}
		sb.WriteString("\n")
	}
	return sb.String()
}

func buildSizedToolList(tools []Tool) (list string, compacted bool, fullBytes int) {
	full := buildToolList(tools)
	return full, false, len(full)
}

// toolBridgeContractMarker identifies text generated by this gateway. The
// marker is deliberately explicit so migration code can distinguish the
// bridge contract from user-authored content without fuzzy deletion.
const toolBridgeContractMarker = "[notion-manager tool bridge contract v1]"

// toolBridgeFingerprint identifies the complete aliased tool contract. Tool
// order is significant because aliases (action_1, action_2, ...) are assigned
// in that order and are part of the model-visible protocol.
func toolBridgeFingerprint(tools []Tool) string {
	encoded, _ := json.Marshal(tools)
	sum := sha256.Sum256(encoded)
	return hex.EncodeToString(sum[:])[:24]
}

// buildToolBridgeContract creates the one stable bridge instruction that is
// stored at the beginning of a Notion thread. It intentionally contains no
// current REQUEST/ROUTES framing: later turns are sent as ordinary user
// messages and the model keeps using this contract from the thread context.
func buildToolBridgeContract(tools []Tool, update bool) string {
	intro := "This is the stable tool contract for the client conversation. It is bridge configuration, not a user request. " +
		"Do not answer this entry; keep it active for every later user message."
	if update {
		intro = "This is an updated stable tool contract for the client conversation. It replaces the previous tool contract. " +
			"Do not answer this entry; keep this version active for every later user message."
	}
	return fmt.Sprintf(
		"%s\n%s\n\n"+
			"In auto mode, answer directly in natural language when no external operation is needed. "+
			"When a listed tool is needed, return exactly one JSON object of the form "+
			"{\"name\":\"label\",\"arguments\":{...}} and do not add commentary. "+
			"Use only the labels and argument schemas below. After a completed tool result, continue from that result; "+
			"answer naturally when it is sufficient or return another valid tool JSON object when another operation is needed. "+
			"Never claim that an operation succeeded before a completed result is supplied.\n\n"+
			"Available tools:\n%s",
		toolBridgeContractMarker, intro, buildToolList(tools))
}

// addToolBridgeDirective adds a small per-request mode override without
// repeating the full contract. It returns a copy and never mutates the
// caller's client-visible message history.
func addToolBridgeDirective(messages []ChatMessage, directive string) []ChatMessage {
	directive = strings.TrimSpace(directive)
	if directive == "" {
		return cloneChatMessages(messages)
	}
	result := cloneChatMessages(messages)
	lastAssistant := -1
	for i := len(result) - 1; i >= 0; i-- {
		if result[i].Role == "assistant" {
			lastAssistant = i
			break
		}
	}
	// Attach the override to the current client turn only. In a tool
	// continuation the newest input is a tool result (Role=tool), so looking
	// through the whole history would incorrectly modify an old user message
	// that partial-transcript mode does not send again.
	for i := len(result) - 1; i >= 0; i-- {
		if i <= lastAssistant {
			break
		}
		if result[i].Role == "user" && result[i].ToolCallID == "" {
			if strings.TrimSpace(result[i].Content) == "" {
				result[i].Content = directive
			} else {
				result[i].Content = directive + "\n\n" + result[i].Content
			}
			return result
		}
	}
	// Keep a mode override visible to buildPartialContinuationContent even
	// when the current tail contains only tool results.
	return append(result, ChatMessage{Role: "user", Content: directive})
}

func toolBridgeDirective(toolChoiceMode string, aliases map[string]string) string {
	switch {
	case toolChoiceMode == "required":
		return "Tool mode for this request: a tool call is required. Return exactly one valid tool JSON object and do not answer with ordinary prose."
	case strings.HasPrefix(toolChoiceMode, "force:"):
		name := strings.TrimPrefix(toolChoiceMode, "force:")
		if alias, ok := aliases[name]; ok {
			name = alias
		}
		return fmt.Sprintf("Tool mode for this request: call exactly %q and return one valid tool JSON object.", name)
	default:
		return ""
	}
}

func aliasClientTools(tools []Tool) ([]Tool, map[string]string, map[string]string) {
	if len(tools) == 0 {
		return tools, nil, nil
	}

	aliased := make([]Tool, len(tools))
	originalToAlias := make(map[string]string, len(tools))
	aliasToOriginal := make(map[string]string, len(tools))
	for i, tool := range tools {
		alias := fmt.Sprintf("action_%d", i+1)
		original := tool.Function.Name
		aliased[i] = tool
		aliased[i].Function = tool.Function
		aliased[i].Function.Name = alias
		aliased[i].Function.Description = strings.ReplaceAll(tool.Function.Description, original, alias)
		originalToAlias[original] = alias
		aliasToOriginal[alias] = original
	}
	return aliased, originalToAlias, aliasToOriginal
}

func aliasToolNamesInMessages(messages []ChatMessage, originalToAlias map[string]string) []ChatMessage {
	if len(originalToAlias) == 0 {
		return messages
	}
	for i := range messages {
		if alias, ok := originalToAlias[messages[i].Name]; ok {
			messages[i].Name = alias
		}
		for j := range messages[i].ToolCalls {
			if alias, ok := originalToAlias[messages[i].ToolCalls[j].Function.Name]; ok {
				messages[i].ToolCalls[j].Function.Name = alias
			}
		}
	}
	return messages
}

func aliasToolChoice(toolChoice interface{}, originalToAlias map[string]string) interface{} {
	if toolChoice == nil || len(originalToAlias) == 0 {
		return toolChoice
	}
	choice, ok := toolChoice.(map[string]interface{})
	if !ok {
		return toolChoice
	}
	cloned := make(map[string]interface{}, len(choice))
	for key, value := range choice {
		cloned[key] = value
	}
	if name, ok := cloned["name"].(string); ok {
		if alias, exists := originalToAlias[name]; exists {
			cloned["name"] = alias
		}
	}
	if fn, ok := cloned["function"].(map[string]interface{}); ok {
		clonedFunction := make(map[string]interface{}, len(fn))
		for key, value := range fn {
			clonedFunction[key] = value
		}
		if name, ok := clonedFunction["name"].(string); ok {
			if alias, exists := originalToAlias[name]; exists {
				clonedFunction["name"] = alias
			}
		}
		cloned["function"] = clonedFunction
	}
	return cloned
}

