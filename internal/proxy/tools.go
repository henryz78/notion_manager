// buildToolsBlock is retained for callers that need a standalone schema block.
// The active client bridge uses buildToolBridgeContract instead, so this
// legacy formatter is not inserted into every request.
func buildToolsBlock(tools []Tool, family modelFamily) string {
	return buildOpenAIToolsBlock(tools)
}

